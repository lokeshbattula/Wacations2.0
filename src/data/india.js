/** Map centre used to project lon/lat into a flat local plane. */
export const MAP_CENTER = [82.5, 22.5];

/** Equirectangular projection with a cos(lat) squeeze; returns [x, y] in map units. */
export function project([lon, lat], scale = 1) {
  const k = Math.cos((MAP_CENTER[1] * Math.PI) / 180);
  return [(lon - MAP_CENTER[0]) * k * scale, (lat - MAP_CENTER[1]) * scale];
}
